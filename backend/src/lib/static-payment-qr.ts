/**
 * Returns the pre-generated ACLEDA KHQR for an exact USD amount, if one exists.
 * These merchant QR codes already have the amount baked in, so they can only be
 * used when the amount being charged matches the QR exactly.
 */
export function getStaticPaymentQr(amount: number, currency: string): StaticPaymentQr | null {
  if (String(currency).toUpperCase() !== "USD") return null;

  const rounded = Math.round(Number(amount) * 100) / 100;
  const entry = STATIC_PAYMENT_QRS.find((item) => Math.abs(item.amount - rounded) < 0.005);
  if (!entry) return null;

  return {
    amount: entry.amount,
    imageUrl: `/uploads/payment_qrcode/${entry.file}`,
    payload: entry.payload,
  };
}
